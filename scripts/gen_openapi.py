"""Generate the committed OpenAPI documents in `spec/`.

Usage::

    uv run python scripts/gen_openapi.py           # (re)write spec/*.openapi.yaml
    uv run python scripts/gen_openapi.py --check   # exit 1 if the committed files are stale
"""

import argparse
import io
import sys
from pathlib import Path
from typing import Any

from log_master.app import build_app
from logserver.router import openapi_schema
from ruamel.yaml import YAML

SPEC_DIR = Path(__file__).resolve().parent.parent / 'spec'
HEADER = '# Generated by scripts/gen_openapi.py from the pydantic models. Do not edit by hand.\n'


def render(document: dict[str, Any]) -> str:
    """Render an OpenAPI document as YAML."""
    yaml = YAML(typ='safe', pure=True)
    yaml.default_flow_style = False
    yaml.sort_base_mapping_type_on_output = False
    yaml.width = 120
    buffer = io.StringIO()
    yaml.dump(document, buffer)
    return HEADER + buffer.getvalue()


def documents() -> dict[Path, str]:
    """Return the rendered documents keyed by their path."""
    return {
        SPEC_DIR / 'logserver.openapi.yaml': render(openapi_schema()),
        SPEC_DIR / 'log-master.openapi.yaml': render(build_app().openapi()),
    }


def main() -> None:
    """Write or check the documents."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if the committed files differ')
    args = parser.parse_args()
    stale = []
    for path, text in documents().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.write_text(text)
            sys.stdout.write(f'wrote {path}\n')
    if stale:
        sys.stderr.write('stale OpenAPI documents (run scripts/gen_openapi.py):\n' + ''.join(f'  {p}\n' for p in stale))
        sys.exit(1)


if __name__ == '__main__':
    main()
